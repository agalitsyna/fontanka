import click
import click_log
from . import cli

import pandas as pd
import numpy as np

import cooler
from cooltools.api import snipping
from ..lib import *

# Set up logging:
from . import get_logger

logger = get_logger(__name__)


@cli.command()
@click_log.simple_verbosity_option(logger)
@click.argument("cool_path", metavar="COOL_PATH", type=str)
@click.argument("output_path", metavar="OUTPUT_PATH", type=str)
@click.option(
    "--window-size",
    "-W",
    help="Window size for fountains, in basepairs",
    type=int,
    required=True,
)
@click.option(
    "--angle",
    "-A",
    help="Angle between the sides of the fountain. E.g., np.pi/4 is approximately 0.7854",
    type=np.float32,
    required=True,
)
@click.option(
    "--regions",
    "--view",
    help="Regions table, tsv file with chromosome, start, end in each line, no header.",
    type=str,
    default=None,
    required=False,
)
@click.option(
    "--snips",
    "-S",
    help="npy object with stored whole-genome snips",
    type=str,
    default=None,
    required=False,
)
@click.option(
    "--nthreads",
    "-p",
    help="Number of threads to use for generating snips",
    type=int,
    default=1,
    required=False,
)
@click.option(
    "--store-snips",
    help="File for storing the snips. Will have .npy format.",
    type=str,
    default=None,
    required=False,
)
@click.option(
    "--expected",
    help="File with expected table, generated by cooltools. Required only if snips are not provided.",
    type=str,
    default=None,
    required=False,
)
@click.option(
    "--cooltools-version",
    help="cooltools version used to generate expected/snips. Will be used only if the snips file is provided.",
    type=str,
    default="latest",
    required=False,
)
def apply_binary_fountain_mask(
    cool_path,
    output_path,
    regions,
    window_size,
    angle,
    snips,
    nthreads,
    store_snips,
    expected,
    cooltools_version,
):

    logger.info(
        f"""Running fountain calling for: {cool_path}, 
fountain angle:{angle:.5f}, window size: {window_size}"""
    )

    # Determine cooltools version:
    flip_stack_snippets = False
    if cooltools_version != "latest":
        ver_nums = tuple(
            int(x) for x in cooltools_version.strip().split(".") if x.isdigit()
        )
        if ver_nums < (0, 6, 0):
            flip_stack_snippets = True
            logger.info(
                f"Detected cooltools version {cooltools_version}, will flip stack dimensions accordingly."
            )

    # load cooler
    clr = cooler.Cooler(cool_path)
    bins = clr.bins()[:]
    resolution_bp = clr.binsize

    assert (
        window_size % resolution_bp == 0
    ), "Window size should be divisible by resolution"

    # load chromosome regions
    if regions is None: 
        chroms_regions = regions = bioframe.make_viewframe(clr.chromsizes)
    else:
        chroms_regions = pd.read_table(regions, header=None)
        if len(chroms_regions.columns) == 3:
            chroms_regions.columns = ["chrom", "start", "end"]
            chroms_regions.loc[:, "name"] = chroms_regions.apply(
                lambda x: f"{x.chrom}:{x.start}-{x.end}", axis=1
            )
        elif len(chroms_regions.columns) == 4:
            chroms_regions.columns = ["chrom", "start", "end", "name"]
        else:
            raise ValueError(
                "Regions table should have 3 or 4 columns and no header. Comply with Open2C viewframe format."
        )

    # create genome-wide windows:
    windows = snipping.make_bin_aligned_windows(
        resolution_bp, bins["chrom"], bins["start"], flank_bp=window_size
    )

    # Assign genomic regions to windows:
    windows = snipping.assign_view_auto(windows, chroms_regions).reset_index(drop=True)

    # Create and store the stack:
    if not snips is None:
        stack = read_snips(snips)
        # Flip the axes if needed:
        if flip_stack_snippets:
            stack = stack.T
    else:
        if not expected is None:
            expected = pd.read_table(expected, header=0)
        stack = generate_ObsExpSnips(
            clr, windows, chroms_regions, expected=expected, nthreads=nthreads
        )
        # Store the stack:
        if not store_snips is None:
            save_snips(stack, store_snips)

    logger.info(f"Finished reading/generating stack, stack shape: {stack.shape}")

    # Create fountain masks
    # First, calculate the number positive and negative values for normalization:
    n_pos = double_triangle_mask(
        angle, window_size // resolution_bp, fill_pos=1, fill_neg=0
    ).sum()
    n_neg = double_triangle_mask(
        angle, window_size // resolution_bp, fill_pos=0, fill_neg=1
    ).sum()
    # All positive values balance out negative values, mask sums up to 0:
    mask_norm = double_triangle_mask(
        angle, window_size // resolution_bp, fill_pos=1 / n_pos, fill_neg=-1 / n_neg
    )
    # Mask sums up to 1:
    mask_pos = double_triangle_mask(
        angle, window_size // resolution_bp, fill_pos=1 / n_pos, fill_neg=0
    )

    # Create track with metadata:
    # Fountain score track:
    fs_track = generate_fountain_score(stack, kernel=mask_norm)
    # Scharr score track (for fountain structure only):
    scharr_track = generate_scharr_score(stack, kernel=mask_pos)
    # Scharr score track (for the whole window):
    scharr_track_box = generate_scharr_score(stack)

    # Write the result, note that bad bins are not filtered out:
    metadata = bins[["chrom", "start", "end"]].copy()
    metadata.loc[:, "window_start"] = windows["start"]
    metadata.loc[:, "window_end"] = windows["end"]
    # Fountain Score (FS) is an average OEE in the fountain divided by average OOE outside of it:
    metadata["FS"] = fs_track
    # Fountain peaks are the prominences of peaks:
    metadata["FS_peaks"] = metadata.groupby("chrom")["FS"].transform(
        get_peaks_prominence
    )
    # Average Scharr in the fountain, which is probably worseassessment of the noise in the window than the "box":
    metadata["Scharr"] = scharr_track
    # Average Scharr for a box:
    metadata["Scharr_box"] = scharr_track_box

    ######################
    ### Store the dataset
    ######################
    logger.info(f"Writing generated metadata into: {output_path}")
    metadata.to_csv(output_path, sep="\t")
